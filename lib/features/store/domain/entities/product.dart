class Product {
  final int id;
  final String nome;
  final double preco;
  final String categoria;
  final String avaliacao;
  final String UrlImagem;


  Product({
    required this.id,
    required this.nome,
    required this.preco,
    required this.categoria,
    required this.avaliacao,
    required this.UrlImagem,
  });
}